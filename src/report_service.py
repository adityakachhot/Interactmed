def _vision_model_available() -> Optional[str]:
    """Return the name of the best available vision model, or None."""
    models = _list_ollama_models()
    for candidate in VISION_CANDIDATES:
        prefix = candidate.split(":")[0]
        for m in models:
            if m == candidate or m.startswith(candidate) or m.startswith(prefix + ":") or m == prefix:
                return m
    return None


def _text_model_available() -> Optional[str]:
    """Return the name of the best available text-only model, or None."""
    models = _list_ollama_models()
    for candidate in [TEXT_MODEL, FALLBACK_TEXT]:
        for m in models:
            if m.startswith(candidate.split(":")[0]):
                return m
    return None


