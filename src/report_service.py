# ── Image utilities ───────────────────────────────────────────────────────────

def _load_to_rgb_array(image_bytes: bytes, image_filename: str) -> np.ndarray:
    """Load DICOM or standard image bytes → uint8 RGB numpy array."""
    import PIL.Image
    suffix = Path(image_filename).suffix.lower()
    if suffix == ".dcm":
        import pydicom
        ds = pydicom.dcmread(io.BytesIO(image_bytes))
        pixels = ds.pixel_array
        # Invert MONOCHROME1 (where 0 is white, max is black) to standard radiological representation
        if getattr(ds, "PhotometricInterpretation", "") == "MONOCHROME1":
            pixels = pixels.max() - pixels
        if pixels.dtype != np.uint8:
            pmin, pmax = pixels.min(), pixels.max()
            pixels = (
                ((pixels - pmin) / (pmax - pmin) * 255).astype(np.uint8)
                if pmax > pmin else np.zeros_like(pixels, dtype=np.uint8)
            )
        if pixels.ndim == 2:
            pixels = np.stack([pixels] * 3, axis=-1)
        elif pixels.ndim == 3 and pixels.shape[2] == 1:
            pixels = np.concatenate([pixels] * 3, axis=-1)
    else:
        pil_img = PIL.Image.open(io.BytesIO(image_bytes)).convert("RGB")
        pixels = np.array(pil_img)
    return pixels


def extract_crop(
    image_bytes: bytes,
    image_filename: str,
    box_pixel_xyxy: list[float],
    margin_px: int = 40,
) -> Optional[np.ndarray]:
    """
    Extract the region crop from [x1,y1,x2,y2] pixel coords with margin.

    Returns uint8 RGB array, or None if box is invalid.
    The crop uses EXACTLY the same coordinates as the overlay renderer.
    """
    import PIL.Image
    pixels = _load_to_rgb_array(image_bytes, image_filename)
    H, W = pixels.shape[:2]

    x1, y1, x2, y2 = [float(v) for v in box_pixel_xyxy]
    # Clamp to image bounds before margin
    x1 = max(0.0, x1)
    y1 = max(0.0, y1)
    x2 = min(float(W), x2)
    y2 = min(float(H), y2)

    if x2 <= x1 or y2 <= y1:
        return None

    # Apply margin (clamped to image bounds)
    cx1 = max(0, int(x1) - margin_px)
    cy1 = max(0, int(y1) - margin_px)
    cx2 = min(W, int(x2) + margin_px)
    cy2 = min(H, int(y2) + margin_px)

    img = PIL.Image.fromarray(pixels)
    crop = img.crop((cx1, cy1, cx2, cy2))
    return np.array(crop)


def _array_to_base64_jpeg(arr: np.ndarray, max_side: int = 512, quality: int = 75) -> str:
    """Resize and encode a numpy RGB array to base64 JPEG (for vision model input)."""
    import PIL.Image
    img = PIL.Image.fromarray(arr)
    # Resize while preserving aspect ratio — vision models don't need full resolution
    w, h = img.size
    if max(w, h) > max_side:
        scale = max_side / max(w, h)
        img = img.resize((int(w * scale), int(h * scale)), PIL.Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=quality)
    return base64.b64encode(buf.getvalue()).decode()


# ── Report validation ─────────────────────────────────────────────────────────

_UNSUPPORTED_MEASUREMENTS = re.compile(
    r'\b\d+\.?\d*\s*(cm|mm|ml|L|mcg|mg|mmHg|HU)\b', re.IGNORECASE
)
_ECHO_ONLY = re.compile(r'^[\s\W]*(\w+[\s\W]*){0,8}$')  # very short


def validate_report(text: str, phrase: str) -> dict:
    """
    Lightweight validation of generated report text.

    Returns dict:
        valid        : bool
        warnings     : list of str describing detected issues
        flagged      : bool — True if output should be flagged for review
    """
    issues = []

    if not text or len(text.strip()) < 30:
        return {"valid": False, "warnings": ["Model returned empty or near-empty response."], "flagged": True}

    stripped = text.strip()

    # Check if response just echoes the phrase without analysis
    words = stripped.lower().split()
    phrase_words = phrase.lower().split()
    if len(words) < 15:
        issues.append("Response is very short — may not contain meaningful analysis.")

    # Detect fabricated measurements (numerical values with units)
    meas_matches = _UNSUPPORTED_MEASUREMENTS.findall(stripped)
    if meas_matches:
        issues.append(
            f"Report contains specific measurements ({', '.join(set(str(m) for m in meas_matches[:3]))}). "
            "These cannot be derived from text metadata alone and may be fabricated."
        )

    # Detect if response is just the phrase repeated
    phrase_clean = re.sub(r'\W+', ' ', phrase).strip().lower()
    response_clean = re.sub(r'\W+', ' ', stripped[:200]).strip().lower()
    if phrase_clean in response_clean and len(words) < 30:
        issues.append("Response appears to merely repeat the target phrase without image analysis.")

    # Detect obvious anatomical contradictions
    lower_text = stripped.lower()
    lower_phrase = phrase.lower()
    if ("cardiomegaly" in lower_phrase or "cardiac" in lower_phrase or "heart" in lower_phrase) and any(
        z in lower_text for z in ["upper lung zone", "upper lobe", "middle lobe", "lung apex", "apical zone", "costophrenic sulcus"]
    ):
        issues.append(
            "Potential anatomical contradiction detected: cardiac abnormality mentioned in a lung zone or apex."
        )
    if "pneumothorax" in lower_phrase and "cardiac silhouette" in lower_text:
        issues.append(
            "Potential anatomical contradiction detected: pneumothorax mentioned in cardiac silhouette."
        )

    # Detect missing disclaimer
    if "experimental" not in stripped.lower() and "not for clinical" not in stripped.lower():
        # Will be appended by caller — note internally only
        pass

    flagged = any("fabricated" in w or "short" in w or "repeat" in w or "contradiction" in w for w in issues)
    return {
        "valid": len([i for i in issues if "fabricated" in i or "repeat" in i or "contradiction" in i]) == 0,
        "warnings": issues,
        "flagged": flagged,
    }


def are_sentences_duplicate(s1: str, s2: str, threshold: float = 0.5) -> bool:
    """Check if two sentences share >threshold fraction of content words."""
    w1 = set(re.findall(r'\b\w{3,}\b', s1.lower()))
    w2 = set(re.findall(r'\b\w{3,}\b', s2.lower()))
    if not w1 or not w2:
        return False
    overlap = len(w1 & w2) / min(len(w1), len(w2))
    return overlap >= threshold


def split_sentences(text: str) -> list[str]:
    """Split text into individual sentences cleanly."""
    raw = re.split(r'(?<=[.!?])\s+|\n+', text)
    return [s.strip() for s in raw if s.strip()]


def clean_and_structure_regional_report(
    raw_text: str,
    phrase: str,
    is_cardiac: bool = False,
) -> tuple[str, list[str]]:
    """
    Parses and structures the four-section regional report:
      1. TARGET FINDING
      2. IMAGE OBSERVATIONS
      3. ASSESSMENT AND UNCERTAINTY
      4. LIMITATIONS

    Guarantees:
      - Observations describe visible evidence without repeating the diagnosis.
      - Assessment provides a clear stance (Supported / Indeterminate / Not supported)
        without repeating observation sentences verbatim.
      - Incidental abnormalities (e.g. lower lung field densities during cardiac queries)
        are clearly separated and labeled as tentative observations requiring review.
      - Erroneous claims of 'cropped view limitation' are removed since full radiograph is provided.
      - Research disclaimer is kept outside the report narrative body.
      - Concise target length (~80-150 words).
    """
    warnings_list: list[str] = []

    pattern = re.compile(
        r'(?:^|\n)\s*(?:\d+[\.\)]\s*)?(?:\*{1,3})?\s*(TARGET FINDING|IMAGE OBSERVATIONS|ASSESSMENT AND UNCERTAINTY|ASSESSMENT|LIMITATIONS)\s*(?:\*{1,3})?\s*:\s*',
        re.IGNORECASE
    )
    matches = list(pattern.finditer(raw_text))

    sections: dict[str, str] = {}
    if matches:
        for i, m in enumerate(matches):
            raw_header = m.group(1).upper()
            sec_name = "ASSESSMENT AND UNCERTAINTY" if "ASSESSMENT" in raw_header else raw_header
            start = m.end()
            end = matches[i + 1].start() if i + 1 < len(matches) else len(raw_text)
            sections[sec_name] = raw_text[start:end].strip()
    else:
        sections["TARGET FINDING"] = phrase
        sections["IMAGE OBSERVATIONS"] = raw_text.strip()
        sections["ASSESSMENT AND UNCERTAINTY"] = ""
        sections["LIMITATIONS"] = ""

    # Strip any leaked disclaimers from inside the narrative (rendered outside by UI)
    disclaimer_pat = re.compile(
        r'(\*{0,2}(?:experimental|not for clinical|ai-generated|consult a radiologist|disclaimer|correlation recommended)[^\n\.]*[\.\n]?)',
        re.IGNORECASE
    )

    # 1. Clean TARGET FINDING
    target_finding = phrase.strip()

    # 2. Clean IMAGE OBSERVATIONS
    raw_obs = sections.get("IMAGE OBSERVATIONS", "").strip()
    raw_obs = disclaimer_pat.sub('', raw_obs).strip()
    obs_sentences = split_sentences(raw_obs)

    clean_obs_sentences = []
    tentative_incidental = []

    incidental_pat = re.compile(
        r'\b(?:increased density|patchy opacit\w+|consolidation|infiltrate\w*|haziness)\s+(?:in|at)\s+(?:the\s+)?(?:lower|basilar|right\s+lower|left\s+lower)\s+lung\s+(?:fields|bases|zones)\b',
        re.IGNORECASE
    )

    for s in obs_sentences:
        if is_cardiac and incidental_pat.search(s):
            if "tentative" in s.lower() or "incidental" in s.lower():
                tentative_incidental.append(s)
            else:
                tentative_incidental.append(
                    f"Tentative incidental observation (requires review): {s}"
                )
                warnings_list.append("Incidental lower lung field density detected in cardiac query; labeled as tentative observation requiring review.")
        else:
            clean_obs_sentences.append(s)

    if not clean_obs_sentences and not tentative_incidental:
        clean_obs_sentences = ["Cardiac silhouette and mediastinal contours evaluated against inner thoracic boundaries on the complete radiograph."] if is_cardiac else [f"Targeted evaluation of region corresponding to {phrase}."]

    obs_body = " ".join(clean_obs_sentences)
    if tentative_incidental:
        obs_body += "\n" + "\n".join(tentative_incidental)

    # 3. Clean ASSESSMENT AND UNCERTAINTY
    raw_assess = sections.get("ASSESSMENT AND UNCERTAINTY", "").strip()
    raw_assess = disclaimer_pat.sub('', raw_assess).strip()
    assess_sentences = split_sentences(raw_assess)

    non_dup_assess = []
    for s in assess_sentences:
        is_dup = False
        for obs_s in clean_obs_sentences:
            if are_sentences_duplicate(s, obs_s, threshold=0.5):
                is_dup = True
                break
        if not is_dup:
            non_dup_assess.append(s)
        else:
            warnings_list.append("Redundant assessment sentence matching image observations was removed.")

    assess_body = " ".join(non_dup_assess).strip()

    bare_prefixes = ["supported:", "indeterminate:", "not supported:", "supported", "indeterminate", "not supported"]
    if not assess_body or assess_body.lower() in bare_prefixes or len(assess_body.split()) <= 2:
        lower_raw = (raw_assess + " " + raw_obs).lower()
        if "not supported" in lower_raw or "no evidence" in lower_raw or "within normal limits" in lower_raw or "normal limits" in lower_raw:
            cat = "Not supported"
            rationale = f"No definitive radiographic evidence of {phrase} is demonstrated on the evaluated projection."
        elif any(w in lower_raw for w in ["supported", "consistent", "demonstrated", "evident", "opacity", "consolidation", "hazy"]):
            cat = "Supported"
            rationale = f"Visible radiographic features are consistent with the queried finding ({phrase}), pending clinical and radiologist verification."
        else:
            cat = "Indeterminate"
            rationale = f"Imaging features remain equivocal and cannot definitively confirm or exclude {phrase} without clinical correlation."
        assess_body = f"{cat}: {rationale}"
    else:
        lower_a = assess_body.lower()
        if not any(assess_body.startswith(p) for p in ["Supported:", "Indeterminate:", "Not supported:"]):
            if "not supported" in lower_a or "no evidence" in lower_a or "excluded" in lower_a:
                assess_body = "Not supported: " + assess_body
            elif any(w in lower_a for w in ["indeterminate", "equivocal", "uncertain", "not definitive", "cannot confirm", "unclear", "not definitively"]):
                assess_body = "Indeterminate: " + assess_body
            elif any(w in lower_a for w in ["supported", "consistent with", "suggests", "demonstrated", "evident"]):
                assess_body = "Supported: " + assess_body
            else:
                assess_body = "Indeterminate: " + assess_body

    # 4. Clean LIMITATIONS
    raw_limit = sections.get("LIMITATIONS", "").strip()
    raw_limit = disclaimer_pat.sub('', raw_limit).strip()

    # Strip any leaked prompt requirement headers
    req_pat = re.compile(r'(?i)\b(?:strict\s+requirements|requirements|strict\s+rules|rules)\b.*$', re.DOTALL)
    raw_limit = req_pat.sub('', raw_limit).strip()

    crop_lim_pat = re.compile(
        r'[^.!?]*\b(?:cropped\s+view|the\s+crop|crop\s*\([^)]*\)|crop\s+alone|crop\s+image|from\s+the\s+crop|limited\s+field\s+of\s+view|magnified\s+crop)\b[^.!?]*[\.!?]?',
        re.IGNORECASE
    )
    cleaned_limit = crop_lim_pat.sub('', raw_limit).strip()

    if not cleaned_limit or cleaned_limit.lower() in ["no limitations.", "none.", "no limitations", "none", "no technical limitations identified.", "no technical limitations identified"]:
        cleaned_limit = (
            "Single-view thoracic projection; definitive evaluation is subject to inspiratory depth, "
            "patient positioning, and the absence of a lateral projection."
        )

    # 5. Assemble final structured report
    final_report = (
        f"TARGET FINDING:\n{target_finding}\n\n"
        f"IMAGE OBSERVATIONS:\n{obs_body}\n\n"
        f"ASSESSMENT AND UNCERTAINTY:\n{assess_body}\n\n"
        f"LIMITATIONS:\n{cleaned_limit}"
    )

    words = final_report.split()
    if len(words) < 40:
        warnings_list.append("Report length is below target concise range.")

    return final_report, warnings_list


# ── Region report (vision-capable) ───────────────────────────────────────────

def region_report(
    image_bytes: bytes,
    image_filename: str,
    phrase: str,
    box_pixel_xyxy: list[float],
    orig_h: int,
    orig_w: int,
    margin_px: int = 40,
) -> dict:
    """
    Generate a region-specific radiology report using a vision-capable model.

    Passes:
      - Image 1 (PRIMARY CONTEXT): Complete thoracic chest radiograph.
      - Image 2 (SUPPLEMENTARY CONTEXT): Magnified crop of predicted region.
      - Phrase evaluated as a hypothesis, NOT a confirmed diagnosis.

    If no vision model is available, returns success=False with a clear error.
    Does NOT fabricate a report from spatial metadata when no image is passed.
    """
    t0 = time.perf_counter()

    # ── Validate box ──────────────────────────────────────────────────────────
    x1, y1, x2, y2 = [float(v) for v in box_pixel_xyxy]
    box_w = x2 - x1
    box_h = y2 - y1

    if box_w <= 0 or box_h <= 0 or orig_w <= 0 or orig_h <= 0:
        return _error_result(t0, f"Invalid bounding box {box_pixel_xyxy} or image dimensions.", None)

    # ── Derive spatial context (kept separate from medical report narrative) ──
    cx_frac = ((x1 + x2) / 2) / orig_w
    cy_frac = ((y1 + y2) / 2) / orig_h
    box_area_pct = round((box_w * box_h) / (orig_w * orig_h) * 100, 2)

    crop_info = {
        "box_pixel_xyxy": box_pixel_xyxy,
        "box_width_px": round(box_w, 1),
        "box_height_px": round(box_h, 1),
        "box_area_pct_of_image": box_area_pct,
        "box_center_x_fraction": round(cx_frac, 3),
        "box_center_y_fraction": round(cy_frac, 3),
        "margin_px_applied": margin_px,
    }

    # ── Check Ollama + vision model ───────────────────────────────────────────
    if not _ollama_available():
        return _error_result(
            t0,
            "Ollama is not reachable (localhost:11434). Start with: ollama serve",
            crop_info,
        )

    vision_model = _vision_model_available()
    if vision_model is None:
        return _error_result(
            t0,
            (
                "No vision-capable model is installed in Ollama. "
                "Install one with: ollama pull medgemma:4b (recommended medical VLM) "
                "or: ollama pull llava:7b\n"
                "A text-only model (llama3/mistral) will NOT be used as a substitute "
                "because it cannot analyse image content."
            ),
            crop_info,
        )

    # ── Extract crop ──────────────────────────────────────────────────────────
    crop_arr = extract_crop(image_bytes, image_filename, box_pixel_xyxy, margin_px)
    if crop_arr is None:
        return _error_result(t0, "Failed to extract image crop from bounding box.", crop_info)

    # ── Encode images for vision model ────────────────────────────────────────
    images_b64 = []
    has_full_image = False
    
    # Image 1 (PRIMARY CONTEXT): Complete thoracic radiograph
    try:
        full_arr = _load_to_rgb_array(image_bytes, image_filename)
        full_b64 = _array_to_base64_jpeg(full_arr, max_side=512)
        images_b64.append(full_b64)
        has_full_image = True
    except Exception:
        pass

    # Image 2 (SUPPLEMENTARY CONTEXT): Magnified crop
    try:
        crop_b64 = _array_to_base64_jpeg(crop_arr, max_side=512)
        images_b64.append(crop_b64)
    except Exception as exc:
        return _error_result(t0, f"Failed to encode crop image: {exc}", crop_info)

    # ── Build prompt ──────────────────────────────────────────────────────────
    if has_full_image:
        image_descriptions = (
            "          Image 1 (PRIMARY CONTEXT): Complete thoracic chest radiograph providing global anatomical context and inner thoracic dimensions.\n"
            f"          Image 2 (SUPPLEMENTARY CONTEXT): Magnified crop centered on the predicted region for \"{phrase}\"."
        )
    else:
        image_descriptions = f"          Image 1: Magnified crop centered on the predicted region for \"{phrase}\"."

    is_global_finding = any(x in phrase.lower() for x in ["cardiomegaly", "heart", "cardiac", "enlarged heart", "cardiomediastinal"])
    
    if is_global_finding and has_full_image:
        context_instruction = (
            "ANATOMICAL EVALUATION FOR CARDIOMEGALY:\n"
            "- Heart size cannot be evaluated from the crop (Image 2) alone.\n"
            "- You must evaluate the cardiac silhouette relative to the maximum inner thoracic width using the complete thoracic radiograph (Image 1).\n"
            "- The prompt phrase is a clinical question, NOT a proven diagnosis. Do not diagnose cardiomegaly simply because it was queried.\n"
            "- If patient rotation, AP portable projection, or submaximal inspiratory effort obscures definitive cardiothoracic ratio, classify as Indeterminate.\n"
            "- Strict focus: Do not introduce unrelated incidental lung base opacities or densities."
        )
    elif has_full_image:
        context_instruction = (
            "ANATOMICAL EVALUATION:\n"
            "- Inspect Image 2 (crop) for localized parenchymal density, texture, and margin characteristics.\n"
            "- Use Image 1 (full radiograph) to establish anatomical zone/lobe and bilateral lung symmetry.\n"
            "- The target phrase is a hypothesis to evaluate, not a confirmed diagnosis. Use cautious, objective language.\n"
            "- Do not introduce unrelated incidental findings unless clearly visible and relevant."
        )
    else:
        context_instruction = "Examine the provided image crop for localized density, borders, and tissue characteristics."

    prompt = textwrap.dedent(f"""
        You are an expert radiology assistant producing a concise, structured draft finding on a chest radiograph.
        Images provided:
{image_descriptions}

        {context_instruction}

        Produce a structured draft finding with EXACTLY the following FOUR sections:

        TARGET FINDING:
        {phrase}

        IMAGE OBSERVATIONS:
        Describe the visible radiographic characteristics (density, opacity, borders, contours, and anatomical landmarks).
        - For cardiac queries: describe the visible cardiac borders and thoracic span; do NOT state a diagnostic conclusion in this section.
        - Strict scope: Do NOT mention unrelated incidental abnormalities (such as lower lung field densities) unless directly relevant. If a relevant incidental finding is genuinely visible, label it on a separate line as: "Tentative incidental observation (requires review): <observation>".

        ASSESSMENT AND UNCERTAINTY:
        Begin with one explicit status: "Supported:", "Indeterminate:", or "Not supported:".
        Follow with ONE concise sentence explaining the clinical impression and uncertainty based on the imaging.
        CRITICAL RULE: Do NOT repeat or paraphrase the physical description sentences from IMAGE OBSERVATIONS.

        LIMITATIONS:
        List genuine technical limitations (e.g. projection type, patient positioning, inspiratory depth, lack of prior comparison).
        NEVER claim your assessment is limited by a "cropped view" or "limited field of view", as you have the full radiograph (Image 1).

        STRICT REQUIREMENTS:
        - Target word count: 80-150 words. Be concise and precise.
        - Do not invent measurements (cm, mm), severity grades, laterality, or findings not visible.
        - Do not include coordinates, box stats, disclaimers, or advice to consult a doctor in the text narrative.

        Begin immediately with TARGET FINDING:
    """).strip()

    # ── Generate ──────────────────────────────────────────────────────────────
    t_prep = time.perf_counter()
    try:
        raw_text = _ollama_generate_vision(prompt, images_b64, model=vision_model)
    except Exception as exc:
        return _error_result(t0, f"Vision model generation failed: {exc}", crop_info)
    t_infer = time.perf_counter()

    if not raw_text:
        return _error_result(t0, "Vision model returned an empty response.", crop_info)

    # ── Clean & Structure 4 sections ──────────────────────────────────────────
    t_post_start = time.perf_counter()
    cleaned_text, clean_warnings = clean_and_structure_regional_report(
        raw_text=raw_text,
        phrase=phrase,
        is_cardiac=is_global_finding,
    )

    # ── Validate ──────────────────────────────────────────────────────────────
    validation = validate_report(cleaned_text, phrase)
    all_warnings = list(dict.fromkeys(clean_warnings + validation["warnings"]))

    report_text = cleaned_text  # Clean narrative body; disclaimer is displayed outside by UI
    t_post = time.perf_counter()
    
    latency_ms = round((t_post - t0) * 1000, 2)
    timing = {
        "prep_ms": round((t_prep - t0) * 1000, 2),
        "inference_ms": round((t_infer - t_prep) * 1000, 2),
        "post_ms": round((t_post - t_post_start) * 1000, 2),
        "total_ms": latency_ms,
    }
    
    return {
        "success": True,
        "error": None,
        "report_text": report_text,
        "crop_info": crop_info,
        "timing": timing,
        "latency_ms": latency_ms,
        "model_used": vision_model,
        "image_input_used": True,
        "n_images_sent": len(images_b64),
        "validation_warnings": all_warnings,
        "validation_flagged": validation["flagged"] or any("detected" in w for w in clean_warnings),
    }


# ── Patient-Friendly Report (Vision-Required) ────────────────────────────────

PATIENT_REPORT_DISCLAIMER = (
    "AI-generated explanation for educational purposes only. It may contain errors and cannot diagnose a condition "
    "or replace professional medical advice. Please discuss your X-ray results with a qualified healthcare professional."
)


def clean_and_structure_patient_report(
    raw_text: str,
    reason: Optional[str] = None,
) -> tuple[str, dict[str, str], list[str]]:
    """
    Parses and structures the four-section patient-friendly explanation:
      1. Your X-ray in simple words
      2. What the findings may mean
      3. What is uncertain
      4. What happens next

    Enforces clinical integrity:
      - Corrects erroneous claims that a frontal view shows only one side of the chest.
      - Strips leaked prompt instructions or disclaimers.
      - Employs cautious inconclusive fallbacks rather than defaulting to normal.
    """
    warnings: list[str] = []

    # 1. Correct the anatomical misconception if hallucinated by the model
    one_side_patterns = [
        re.compile(r'(?:because\s+)?this\s+is\s+a\s+frontal\s+view(?:\s+of\s+the\s+chest)?,\s*(?:it\s+)?only\s+shows\s+one\s+side(?:\s+of\s+(?:your|the)\s+chest)?(?:\s+at\s+a\s+time)?\.?', re.IGNORECASE),
        re.compile(r'(?:it\s+)?only\s+shows\s+one\s+side\s+of\s+(?:your|the)\s+chest(?:\s+at\s+a\s+time)?\.?', re.IGNORECASE),
        re.compile(r'shows\s+only\s+one\s+side\s+of\s+(?:your|the)\s+chest(?:\s+at\s+a\s+time)?\.?', re.IGNORECASE),
        re.compile(r'only\s+shows\s+one\s+side\s+at\s+a\s+time\.?', re.IGNORECASE),
        re.compile(r'only\s+shows\s+one\s+side(?:\s+of\s+the\s+chest)?\.?', re.IGNORECASE),
    ]
    corrected_side_statement = (
        "This frontal view displays both the left and right sides of the chest, "
        "but as a single 2D projection, it does not provide a side (lateral) view."
    )
    for pat in one_side_patterns:
        if pat.search(raw_text):
            raw_text = pat.sub(corrected_side_statement, raw_text)
            warnings.append(
                "Corrected anatomical error: A frontal view displays both sides of the chest, but lacks a lateral projection."
            )

    # 2. Strip leaked prompt instructions or templates
    prompt_leak_patterns = [
        re.compile(r'Explain the observed visual features in plain[^\n\.]*[\.\n]?', re.IGNORECASE),
        re.compile(r'Mention any shading, opacities, or medical devices[^\n\.]*[\.\n]?', re.IGNORECASE),
        re.compile(r'If the observation indicates uncertainty[^\n\.]*[\.\n]?', re.IGNORECASE),
        re.compile(r'Describe the visible shading and shapes[^\n\.]*[\.\n]?', re.IGNORECASE),
        re.compile(r'Translate these observed findings into[^\n\.]*[\.\n]?', re.IGNORECASE),
    ]
    for pat in prompt_leak_patterns:
        raw_text = pat.sub('', raw_text)

    # 3. Section headers regex
    pattern = re.compile(
        r'(?:^|\n)\s*(?:\d+[\.\)]\s*)?(?:\*{1,3})?\s*(Your X-ray in simple words|What the findings may mean|What is uncertain|What happens next)\s*(?:\*{1,3})?\s*[:\n]?',
        re.IGNORECASE
    )
    matches = list(pattern.finditer(raw_text))

    sections: dict[str, str] = {}
    if matches:
        for i, m in enumerate(matches):
            header = m.group(1).strip()
            std_header = "Your X-ray in simple words"
            for target in ["Your X-ray in simple words", "What the findings may mean", "What is uncertain", "What happens next"]:
                if target.lower() == header.lower():
                    std_header = target
                    break
            start = m.end()
            end = matches[i + 1].start() if i + 1 < len(matches) else len(raw_text)
            sections[std_header] = raw_text[start:end].strip()
    else:
        sections["Your X-ray in simple words"] = raw_text.strip()
        sections["What the findings may mean"] = ""
        sections["What is uncertain"] = ""
        sections["What happens next"] = ""

    # Strip any leaked disclaimers from the narrative
    disclaimer_pat = re.compile(
        r'(\*{0,2}(?:experimental|not for clinical|ai-generated explanation|educational purposes only|consult a doctor|consult your doctor|disclaimer)[^\n\.]*[\.\n]?)',
        re.IGNORECASE
    )
    for k in sections:
        sections[k] = disclaimer_pat.sub('', sections[k]).strip()

    # Fallback content for empty sections — cautious and inconclusive
    if not sections.get("Your X-ray in simple words"):
        sections["Your X-ray in simple words"] = (
            "The automated visual assessment of this chest radiograph is inconclusive and requires clinical review."
        )

    if not sections.get("What the findings may mean"):
        sections["What the findings may mean"] = (
            "The visual features require correlation with your clinical symptoms and medical history by a licensed physician."
        )

    if not sections.get("What is uncertain"):
        sections["What is uncertain"] = (
            "This frontal view displays both the left and right sides of the chest, but because it is a single two-dimensional "
            "projection without a side (lateral) view, subtle findings or depth cannot be confirmed by AI alone."
        )

    if not sections.get("What happens next"):
        sections["What happens next"] = (
            "Please discuss these results with the healthcare professional who ordered your X-ray. They will combine this image with your "
            "symptoms and medical background to guide your care."
        )

    # Detect ungrounded boilerplate claims and add warnings
    for k, v in sections.items():
        if re.search(r'bones(?:\s+of\s+your\s+chest\s+wall)?\s+(?:look|appear)\s+intact', v, re.IGNORECASE):
            warnings.append("Ungrounded assertion: Bone integrity claimed without dedicated rib assessment.")
        if re.search(r'no\s+obvious\s+signs\s+of\s+infection\s+or\s+fluid', v, re.IGNORECASE):
            warnings.append("Ungrounded assertion: Absolute absence of infection/fluid asserted from single AI draft.")

    # Detect unsupported numerical measurements
    for k, v in sections.items():
        meas = _UNSUPPORTED_MEASUREMENTS.findall(v)
        if meas:
            warnings.append(
                f"Section '{k}' contains specific measurements ({', '.join(set(meas))}). "
                "These cannot be derived reliably from a single AI draft."
            )

    full_text = (
        f"**Your X-ray in simple words**\n{sections['Your X-ray in simple words']}\n\n"
        f"**What the findings may mean**\n{sections['What the findings may mean']}\n\n"
        f"**What is uncertain**\n{sections['What is uncertain']}\n\n"
        f"**What happens next**\n{sections['What happens next']}"
    )

    words = full_text.split()
    if len(words) < 50:
        warnings.append("Explanation is very brief — key details may be omitted.")
    elif len(words) > 280:
        warnings.append("Explanation is longer than standard patient-friendly target (100–180 words).")

    return full_text, sections, warnings


def patient_friendly_report(
    image_bytes: Optional[bytes],
    image_filename: str,
    reason_for_xray: Optional[str] = None,
    relevant_history: Optional[str] = None,
) -> dict:
    """
    Generate an accessible, plain-language patient explanation of a chest radiograph.
    
    Guarantees:
      - Uses image-capable VLM (e.g. medgemma:4b) with the full radiograph as primary input.
      - Never fabricates a report from text context alone if image input is missing or unreadable.
      - Structures output into:
          1. Your X-ray in simple words
          2. What the findings may mean
          3. What is uncertain
          4. What happens next
      - Uses calm, respectful language and immediately explains medical terminology.
      - Disclaimers and metadata are kept outside the explanation narrative.
    """
    t0 = time.perf_counter()

    # 1. Image presence validation
    if image_bytes is None or len(image_bytes) < 100:
        return {
            "success": False,
            "error": "A valid chest radiograph image is required. An explanation cannot be generated without an image input.",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": None,
            "image_input_used": False,
            "validation_warnings": ["No image input provided."],
            "validation_flagged": True,
        }

    # 2. Decode image to RGB array
    try:
        full_arr = _load_to_rgb_array(image_bytes, image_filename)
        if full_arr is None or full_arr.size == 0:
            raise ValueError("Decoded image array is empty.")
        full_b64 = _array_to_base64_jpeg(full_arr, max_side=1024, quality=85)
    except Exception as exc:
        return {
            "success": False,
            "error": f"Invalid or unreadable image file ({image_filename}): {exc}. Please upload a valid DICOM or standard image (PNG, JPG).",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": None,
            "image_input_used": False,
            "validation_warnings": [f"Image decode failed: {exc}"],
            "validation_flagged": True,
        }

    # 3. Check Ollama & vision model availability
    if not _ollama_available():
        return {
            "success": False,
            "error": "Ollama is not reachable (localhost:11434). Start with: ollama serve",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": None,
            "image_input_used": False,
            "validation_warnings": [],
            "validation_flagged": False,
        }

    vision_model = _vision_model_available()
    if vision_model is None:
        return {
            "success": False,
            "error": (
                "No vision-capable model is installed in Ollama. "
                "A vision model (such as medgemma:4b or llava:7b) is required to inspect the chest radiograph. "
                "Text-only models are not permitted as a substitute."
            ),
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": None,
            "image_input_used": False,
            "validation_warnings": ["No vision-capable model available."],
            "validation_flagged": True,
        }

    # 4. Context preparation (patient-reported, non-binding)
    context_lines = []
    if reason_for_xray and reason_for_xray.strip():
        context_lines.append(f"- Reason for examination (patient-reported): {reason_for_xray.strip()[:300]}")
    if relevant_history and relevant_history.strip():
        context_lines.append(f"- Medical history (patient-reported): {relevant_history.strip()[:500]}")

    context_str = "\n".join(context_lines) if context_lines else "None provided by the patient."

    # 5. Two-Stage Grounded Generation:
    # Step 1: Extract direct radiographic observations from full 1024px image
    v_prompt = (
        "Look at this chest radiograph carefully. "
        "Describe what visible abnormalities, densities, or opacities are present in the lungs, cardiac silhouette, and any lines, tubes, or devices. "
        "Be objective and specific about whether the lungs appear clear or if opacities are present."
    )
    t_prep = time.perf_counter()
    try:
        raw_obs = _ollama_generate_vision(v_prompt, [full_b64], model=vision_model)
    except Exception as exc:
        return {
            "success": False,
            "error": f"Model vision extraction failed: {exc}",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": vision_model,
            "image_input_used": True,
            "validation_warnings": [str(exc)],
            "validation_flagged": True,
        }

    # Step 2: Patient-friendly translation strictly reflecting extracted observations
    p_prompt = textwrap.dedent(f"""
        A medical vision model examined this patient's frontal chest X-ray and reported these visual observations:
        \"\"\"{raw_obs}\"\"\"

        PATIENT BACKGROUND (context only):
        {context_str}

        Translate these observed findings into an accessible, patient-friendly explanation.
        Use EXACTLY these four headings:

        Your X-ray in simple words
        Describe only the visual features noted above in plain language. If opacities, lung shading, or medical devices are present, describe where they are. If visual findings are ambiguous or inconclusive, state: "The automated visual reading is inconclusive."

        What the findings may mean
        Explain what these observed findings could suggest in everyday words. Explain any medical terminology simply. Do not assume or assert that the scan is completely normal if opacities were noted.

        What is uncertain
        Explain what cannot be determined from this view. Clarify that this frontal view displays both the left and right sides of the chest, but because it is a single two-dimensional projection without a side (lateral) view, depth and subtle findings cannot be confirmed.

        What happens next
        Advise the patient to consult their ordering physician for qualified clinical evaluation and diagnosis.

        STRICT RULES:
        - NEVER say a frontal view shows only one side of the chest; a frontal view shows both sides of the chest.
        - Do not invent normal findings or declare absence of infection unless clearly supported.
        - Do not suggest specific medications or medical treatments.

        Begin directly with:
        Your X-ray in simple words
    """).strip()

    try:
        raw_text = _ollama_generate_text(p_prompt, model=vision_model)
    except Exception as exc:
        return {
            "success": False,
            "error": f"Model explanation structuring failed: {exc}",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": vision_model,
            "image_input_used": True,
            "validation_warnings": [str(exc)],
            "validation_flagged": True,
        }
    t_infer = time.perf_counter()

    if not raw_text:
        return {
            "success": False,
            "error": "Model returned an empty response.",
            "report_text": None,
            "sections": None,
            "latency_ms": round((time.perf_counter() - t0) * 1000, 2),
            "timing": None,
            "model_used": vision_model,
            "image_input_used": True,
            "validation_warnings": ["Empty model output."],
            "validation_flagged": True,
        }

    # 7. Post-process & Structure
    full_text, sections, warnings = clean_and_structure_patient_report(raw_text, reason=reason_for_xray)
    t_post = time.perf_counter()

    # 8. Triage Evaluation
    triage_eval = get_triage_service().evaluate_from_report_text(full_text, sections)

    latency_ms = round((t_post - t0) * 1000, 2)
    timing = {
        "prep_ms": round((t_prep - t0) * 1000, 2),
        "inference_ms": round((t_infer - t_prep) * 1000, 2),
        "post_ms": round((t_post - t_infer) * 1000, 2),
        "total_ms": latency_ms,
    }

    return {
        "success": True,
        "error": None,
        "report_text": full_text,
        "sections": sections,
        "triage_result": triage_eval.to_dict(),
        "timing": timing,
        "latency_ms": latency_ms,
        "model_used": vision_model,
        "image_input_used": True,
        "validation_warnings": warnings,
        "validation_flagged": len([w for w in warnings if "measurement" in w or "brief" in w]) > 0,
    }


def study_report(
    image_bytes: Optional[bytes],
    image_filename: str,
    orig_h: int = 0,
    orig_w: int = 0,
    clinical_indication: str = "",
    relevant_history: Optional[str] = None,
    prior_report: Optional[str] = None,
    grounding_results: Optional[list] = None,
) -> dict:
    """Compatibility wrapper that routes study report requests to patient_friendly_report."""
    return patient_friendly_report(
        image_bytes=image_bytes,
        image_filename=image_filename,
        reason_for_xray=clinical_indication,
        relevant_history=relevant_history,
    )


